func (s *session) Schemas(ctx context.Context) ([]string, error) {
	return s.strings(ctx, `SELECT nspname::text FROM pg_namespace
		WHERE nspname !~ '^pg_(toast|temp)' AND nspname NOT IN ('information_schema', 'pg_catalog') ORDER BY 1`)
}

var kindOf = map[string]db.Kind{"table": db.KindTable, "view": db.KindView, "matview": db.KindMatView,
	"function": db.KindFunction, "procedure": db.KindProcedure, "sequence": db.KindSequence, "type": db.KindType}

func (s *session) Objects(ctx context.Context, schema string) ([]db.Object, error) {
	if schema == "" {
		schema = s.CurrentSchema()
	}
	var out []db.Object
	err := s.query(ctx, `SELECT k, name, detail FROM (
		SELECT CASE c.relkind WHEN 'v' THEN 'view' WHEN 'm' THEN 'matview' WHEN 'S' THEN 'sequence' ELSE 'table' END AS k, c.relname::text AS name,
			-- catalog estimate (pages as of the last VACUUM/ANALYZE): pg_total_relation_size stats every
			-- file of every relation and makes the sidebar crawl on schemas with thousands of tables
			CASE WHEN c.relkind IN ('r','p','m') AND c.relpages > 0
				THEN pg_size_pretty(c.relpages::bigint * current_setting('block_size')::bigint) ELSE '' END AS detail
		FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
		WHERE n.nspname = $1 AND c.relkind IN ('r','p','v','m','S','f')
		  AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.classid = 'pg_class'::regclass AND d.objid = c.oid AND d.deptype = 'e')
		UNION ALL
		SELECT CASE p.prokind WHEN 'p' THEN 'procedure' ELSE 'function' END, p.proname::text, '(' || pg_get_function_identity_arguments(p.oid) || ')'
		FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
		WHERE n.nspname = $1 AND p.prokind IN ('f','p')
		  AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.classid = 'pg_proc'::regclass AND d.objid = p.oid AND d.deptype = 'e')
		UNION ALL
		SELECT 'type', t.typname::text, CASE t.typtype WHEN 'e' THEN 'enum' WHEN 'd' THEN 'domain' ELSE 'composite' END
		FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
		WHERE n.nspname = $1 AND (t.typtype IN ('e','d') OR (t.typtype = 'c' AND EXISTS (SELECT 1 FROM pg_class c WHERE c.oid = t.typrelid AND c.relkind = 'c')))
	) o ORDER BY CASE k WHEN 'table' THEN 1 WHEN 'view' THEN 2 WHEN 'matview' THEN 3 WHEN 'function' THEN 4 WHEN 'procedure' THEN 5 WHEN 'sequence' THEN 6 ELSE 7 END, name, detail`,
		[]any{schema}, func(r pgx.Rows) error {
			var k, name, detail string
			if err := r.Scan(&k, &name, &detail); err != nil {
				return err
			}
			out = append(out, db.Object{ObjRef: db.ObjRef{Schema: schema, Name: name, Kind: kindOf[k]}, Detail: detail})
			return nil
		})
	if err != nil {
		return nil, fmt.Errorf("list objects: %w", err)
	}
	return out, nil
}

func (s *session) columns(ctx context.Context, ref db.ObjRef) ([]db.Column, error) {
	ref = s.ref(ref)
	var out []db.Column
	err := s.query(ctx, `SELECT a.attname::text, format_type(a.atttypid, a.atttypmod), NOT a.attnotnull,
			coalesce(pg_get_expr(d.adbin, d.adrelid), ''), a.attidentity::text, a.attgenerated::text,
			pg_get_serial_sequence(format('%I.%I', n.nspname, c.relname), a.attname) IS NOT NULL,
			EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conrelid = c.oid AND k.contype = 'p' AND a.attnum = ANY (k.conkey))
		FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid JOIN pg_namespace n ON n.oid = c.relnamespace
		LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
		WHERE n.nspname = $1 AND c.relname = $2 AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum`,
		[]any{ref.Schema, ref.Name}, func(r pgx.Rows) error {
			var c db.Column
			var def, ident, gen string
			var owned bool // the default's sequence belongs to the column (serial), not one the user created
			if err := r.Scan(&c.Name, &c.Type, &c.Nullable, &def, &ident, &gen, &owned, &c.PK); err != nil {
				return err
			}
			switch {
			case gen == "s":
				c.Extra = "GENERATED ALWAYS AS (" + def + ") STORED"
			case ident == "a":
				c.Extra = "GENERATED ALWAYS AS IDENTITY"
			case ident == "d":
				c.Extra = "GENERATED BY DEFAULT AS IDENTITY"
			default:
				c.Default, c.HasDef = def, def != ""
				if owned && strings.HasPrefix(def, "nextval(") {
					c.Extra = "serial"
				}
			}
			out = append(out, c)
			return nil
		})
	if err != nil {
		return nil, fmt.Errorf("list columns of %s: %w", ref.Name, err)
	}
	return out, nil
}

func (s *session) Columns(ctx context.Context, ref db.ObjRef) ([]db.Column, error) {
	cols, err := s.columns(ctx, ref)
	if err != nil {
		return nil, err
	}
	fks, err := s.ForeignKeys(ctx, ref)
	if err != nil {
		return nil, err
	}
	for i := range fks {
		for _, name := range fks[i].Columns {
			for j := range cols {
				if cols[j].Name == name {
					cols[j].FK = &fks[i]
				}
			}
		}
	}
	return cols, nil
}

func (s *session) Indexes(ctx context.Context, ref db.ObjRef) ([]db.Index, error) {
	ref = s.ref(ref)
	var out []db.Index
	err := s.query(ctx, `SELECT ic.relname::text, i.indisunique, i.indisprimary, am.amname::text, coalesce(pg_get_expr(i.indpred, i.indrelid), ''),
			(SELECT coalesce(array_agg(CASE WHEN i.indkey[k - 1] <> 0
				THEN (SELECT a.attname::text FROM pg_attribute a WHERE a.attrelid = i.indrelid AND a.attnum = i.indkey[k - 1])
				ELSE pg_get_indexdef(i.indexrelid, k, true) END ORDER BY k), '{}')::text[] FROM generate_series(1, i.indnkeyatts::int) k)
		FROM pg_index i JOIN pg_class ic ON ic.oid = i.indexrelid JOIN pg_class c ON c.oid = i.indrelid
		JOIN pg_namespace n ON n.oid = c.relnamespace JOIN pg_am am ON am.oid = ic.relam
		WHERE n.nspname = $1 AND c.relname = $2 ORDER BY i.indisprimary DESC, ic.relname`,
		[]any{ref.Schema, ref.Name}, func(r pgx.Rows) error {
			var ix db.Index
			if err := r.Scan(&ix.Name, &ix.Unique, &ix.Primary, &ix.Algorithm, &ix.Condition, &ix.Columns); err != nil {
				return err
			}
			out = append(out, ix)
			return nil
		})
	if err != nil {
		return nil, fmt.Errorf("list indexes of %s: %w", ref.Name, err)
	}
	return out, nil
}

var trigRe = regexp.MustCompile(`^CREATE (?:CONSTRAINT )?TRIGGER (?:"(?:[^"]|"")*"|\S+) (BEFORE|AFTER|INSTEAD OF) (.+?) ON `)

// parseTrigger splits pg_get_triggerdef output into timing, event and the "FOR EACH ... EXECUTE ..." tail.
func parseTrigger(name, def string) db.Trigger {
	t := db.Trigger{Name: name, Statement: def}
	if m := trigRe.FindStringSubmatch(def); m != nil {
		t.Timing, t.Event = m[1], m[2]
	}
	for _, marker := range []string{" FOR EACH ", " EXECUTE "} {
		if i := strings.Index(def, marker); i >= 0 {
			t.Statement = def[i+1:]
			break
		}
	}
	return t
}

func (s *session) Triggers(ctx context.Context, ref db.ObjRef) ([]db.Trigger, error) {
	ref = s.ref(ref)
	var out []db.Trigger
	err := s.query(ctx, `SELECT t.tgname::text, pg_get_triggerdef(t.oid)
		FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace
		WHERE n.nspname = $1 AND c.relname = $2 AND NOT t.tgisinternal ORDER BY t.tgname`,
		[]any{ref.Schema, ref.Name}, func(r pgx.Rows) error {
			var name, def string
			if err := r.Scan(&name, &def); err != nil {
				return err
			}
			out = append(out, parseTrigger(name, def))
			return nil
		})
	if err != nil {
		return nil, fmt.Errorf("list triggers of %s: %w", ref.Name, err)
	}
	return out, nil
}

var fkActions = map[string]string{"a": "NO ACTION", "r": "RESTRICT", "c": "CASCADE", "n": "SET NULL", "d": "SET DEFAULT"}

func (s *session) ForeignKeys(ctx context.Context, ref db.ObjRef) ([]db.ForeignKey, error) {
	ref = s.ref(ref)
	var out []db.ForeignKey
	err := s.query(ctx, `SELECT con.conname::text,
			(SELECT array_agg(a.attname::text ORDER BY k.ord) FROM unnest(con.conkey) WITH ORDINALITY k(attnum, ord) JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum)::text[],
			rn.nspname::text, rc.relname::text,
			(SELECT array_agg(a.attname::text ORDER BY k.ord) FROM unnest(con.confkey) WITH ORDINALITY k(attnum, ord) JOIN pg_attribute a ON a.attrelid = con.confrelid AND a.attnum = k.attnum)::text[],
			con.confupdtype::text, con.confdeltype::text
		FROM pg_constraint con JOIN pg_class c ON c.oid = con.conrelid JOIN pg_namespace n ON n.oid = c.relnamespace
		JOIN pg_class rc ON rc.oid = con.confrelid JOIN pg_namespace rn ON rn.oid = rc.relnamespace
		WHERE con.contype = 'f' AND n.nspname = $1 AND c.relname = $2 ORDER BY con.conname`,
		[]any{ref.Schema, ref.Name}, func(r pgx.Rows) error {
			var fk db.ForeignKey
			var upd, del string
			if err := r.Scan(&fk.Name, &fk.Columns, &fk.RefSchema, &fk.RefTable, &fk.RefColumns, &upd, &del); err != nil {
				return err
			}
			fk.OnUpdate, fk.OnDelete = fkActions[upd], fkActions[del]
			out = append(out, fk)
			return nil
		})
	if err != nil {
		return nil, fmt.Errorf("list foreign keys of %s: %w", ref.Name, err)
	}
	return out, nil
}

// notFound turns an empty result into an error.
func notFound(what string, err error) error {
	if err != nil {
		return fmt.Errorf("%s: %w", what, err)
	}
	return fmt.Errorf("%s: not found", what)
}

func (s *session) DDL(ctx context.Context, ref db.ObjRef) (string, error) {
	ref = s.ref(ref)
	qn := db.PG.QualifiedName(ref)
	switch ref.Kind {
	case db.KindView, db.KindMatView:
		defs, err := s.strings(ctx, `SELECT pg_get_viewdef(c.oid, true) FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
			WHERE n.nspname = $1 AND c.relname = $2`, ref.Schema, ref.Name)
		if err != nil || len(defs) == 0 {
			return "", notFound("view definition of "+ref.Name, err)
		}
		def := strings.TrimSuffix(strings.TrimSpace(defs[0]), ";")
		if ref.Kind == db.KindView {
			return "CREATE OR REPLACE VIEW " + qn + " AS\n" + def + ";", nil
		}
		idx, err := s.indexDefs(ctx, ref)
		if err != nil {
			return "", err
		}
		return strings.Join(append([]string{"CREATE MATERIALIZED VIEW " + qn + " AS\n" + def + ";"}, idx...), "\n"), nil
	case db.KindFunction, db.KindProcedure:
		defs, err := s.strings(ctx, `SELECT pg_get_functiondef(p.oid) FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
			WHERE n.nspname = $1 AND p.proname = $2 AND p.prokind IN ('f','p') ORDER BY p.oid`, ref.Schema, ref.Name)
		if err != nil || len(defs) == 0 {
			return "", notFound("function definition of "+ref.Name, err)
		}
		for i, d := range defs {
			defs[i] = strings.TrimSpace(d) + ";"
		}
		return strings.Join(defs, "\n\n"), nil
	case db.KindSequence:
		return s.sequenceDDL(ctx, ref, qn)
	case db.KindType:
		return s.typeDDL(ctx, ref, qn)
	}
	return s.tableDDL(ctx, ref, qn)
}

func (s *session) indexDefs(ctx context.Context, ref db.ObjRef) ([]string, error) {
	defs, err := s.strings(ctx, `SELECT pg_get_indexdef(i.indexrelid) || ';' FROM pg_index i JOIN pg_class c ON c.oid = i.indrelid
		JOIN pg_namespace n ON n.oid = c.relnamespace
		WHERE n.nspname = $1 AND c.relname = $2 AND NOT i.indisprimary
		  AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid = i.indexrelid AND k.contype IN ('u','x','p'))
		ORDER BY 1`, ref.Schema, ref.Name)
	if err != nil {
		return nil, fmt.Errorf("index definitions: %w", err)
	}
	return defs, nil
}

func (s *session) tableDDL(ctx context.Context, ref db.ObjRef, qn string) (string, error) {
	// a plain CREATE TABLE would silently describe a different object
	odd, err := s.strings(ctx, `SELECT CASE WHEN c.relkind = 'f' THEN 'foreign table' ELSE 'partition' END FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
		WHERE n.nspname = $1 AND c.relname = $2 AND (c.relkind = 'f' OR c.relispartition)`, ref.Schema, ref.Name)
	if err != nil {
		return "", err
	}
	if len(odd) > 0 {
		return "", fmt.Errorf("%s is a %s: a create script is not supported for it", ref.Name, odd[0])
	}
	cols, err := s.columns(ctx, ref)
	if err != nil {
		return "", err
	}
	if len(cols) == 0 {
		return "", fmt.Errorf("table %s not found", ref.Name)
	}
	var parts, pre, post []string
	for _, c := range cols {
		parts = append(parts, "  "+columnSQL(c))
		if c.Extra != "serial" {
			continue
		}
		// the serial's own sequence: created first (dropping the table drops it), owned by the column after, like pg_dump
		seq, err := s.strings(ctx, `SELECT pg_get_serial_sequence($1, $2)`, qn, c.Name)
		if err != nil {
			return "", err
		}
		for _, sq := range seq {
			pre = append(pre, "CREATE SEQUENCE IF NOT EXISTS "+sq+";")
			post = append(post, "ALTER SEQUENCE "+sq+" OWNED BY "+qn+"."+ident(c.Name)+";")
		}
	}
	cons, err := s.strings(ctx, `SELECT 'CONSTRAINT ' || quote_ident(con.conname) || ' ' || pg_get_constraintdef(con.oid)
		FROM pg_constraint con JOIN pg_class c ON c.oid = con.conrelid JOIN pg_namespace n ON n.oid = c.relnamespace
		WHERE n.nspname = $1 AND c.relname = $2 AND con.contype IN ('p','u','c','x','f')
		ORDER BY CASE con.contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'c' THEN 2 WHEN 'x' THEN 3 ELSE 4 END, con.conname`, ref.Schema, ref.Name)
	if err != nil {
		return "", fmt.Errorf("constraint definitions: %w", err)
	}
	for _, c := range cons {
		parts = append(parts, "  "+c)
	}
	ddl := "CREATE TABLE " + qn + " (\n" + strings.Join(parts, ",\n") + "\n)"
	partBy, err := s.strings(ctx, `SELECT pg_get_partkeydef(c.oid) FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
		WHERE n.nspname = $1 AND c.relname = $2 AND c.relkind = 'p'`, ref.Schema, ref.Name)
	if err != nil {
		return "", err
	}
	if len(partBy) > 0 {
		ddl += " PARTITION BY " + partBy[0]
	}
	idx, err := s.indexDefs(ctx, ref)
	if err != nil {
		return "", err
	}
	return strings.Join(append(append(pre, ddl+";"), append(idx, post...)...), "\n"), nil
}

func (s *session) sequenceDDL(ctx context.Context, ref db.ObjRef, qn string) (string, error) {
	var typ string
	var start, inc, lo, hi, cache int64
	var cycle, found bool
	err := s.query(ctx, `SELECT data_type::text, start_value, increment_by, min_value, max_value, cache_size, cycle
		FROM pg_sequences WHERE schemaname = $1 AND sequencename = $2`, []any{ref.Schema, ref.Name}, func(r pgx.Rows) error {
		found = true
		return r.Scan(&typ, &start, &inc, &lo, &hi, &cache, &cycle)
	})
	if err != nil || !found {
		return "", notFound("sequence definition of "+ref.Name, err)
	}
	cy := "NO CYCLE"
	if cycle {
		cy = "CYCLE"
	}
	return fmt.Sprintf("CREATE SEQUENCE %s AS %s INCREMENT BY %d MINVALUE %d MAXVALUE %d START WITH %d CACHE %d %s;", qn, typ, inc, lo, hi, start, cache, cy), nil
}

func (s *session) typeDDL(ctx context.Context, ref db.ObjRef, qn string) (string, error) {
	kind, err := s.strings(ctx, `SELECT t.typtype::text FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace WHERE n.nspname = $1 AND t.typname = $2`, ref.Schema, ref.Name)
	if err != nil || len(kind) == 0 {
		return "", notFound("type definition of "+ref.Name, err)
	}
	switch kind[0] {
	case "e":
		labels, err := s.strings(ctx, `SELECT quote_literal(e.enumlabel) FROM pg_enum e JOIN pg_type t ON t.oid = e.enumtypid JOIN pg_namespace n ON n.oid = t.typnamespace
			WHERE n.nspname = $1 AND t.typname = $2 ORDER BY e.enumsortorder`, ref.Schema, ref.Name)
		return "CREATE TYPE " + qn + " AS ENUM (" + strings.Join(labels, ", ") + ");", err
	case "c":
		attrs, err := s.strings(ctx, `SELECT quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod) FROM pg_attribute a JOIN pg_type t ON t.typrelid = a.attrelid
			JOIN pg_namespace n ON n.oid = t.typnamespace WHERE n.nspname = $1 AND t.typname = $2 AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum`, ref.Schema, ref.Name)
		return "CREATE TYPE " + qn + " AS (" + strings.Join(attrs, ", ") + ");", err
	case "d":
		d, err := s.strings(ctx, `SELECT format_type(t.typbasetype, t.typtypmod) || CASE WHEN t.typnotnull THEN ' NOT NULL' ELSE '' END
				|| coalesce(' DEFAULT ' || t.typdefault, '') || coalesce((SELECT ' ' || string_agg(pg_get_constraintdef(c.oid), ' ' ORDER BY c.conname) FROM pg_constraint c WHERE c.contypid = t.oid), '')
			FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace WHERE n.nspname = $1 AND t.typname = $2`, ref.Schema, ref.Name)
		if err != nil || len(d) == 0 {
			return "", notFound("domain definition of "+ref.Name, err)
		}
		return "CREATE DOMAIN " + qn + " AS " + d[0] + ";", nil
	}
	return "", fmt.Errorf("no DDL for type %s", ref.Name)
}

func (s *session) Script(ctx context.Context, kind db.ScriptKind, ref db.ObjRef) (string, error) {
	ref = s.ref(ref)
	op := map[db.ScriptKind]db.AdminOp{db.ScriptDrop: db.OpDropObject, db.ScriptTruncate: db.OpTruncate}[kind]
	switch kind {
	case db.ScriptCreate:
		return s.DDL(ctx, ref)
	case db.ScriptDrop, db.ScriptTruncate:
		sts, err := s.PlanAdmin(op, ref, nil)
		if err != nil {
			return "", err
		}
		return sts[0].Text + ";", nil
	case db.ScriptSelectTop:
		return "SELECT * FROM " + db.PG.QualifiedName(ref) + " LIMIT 100;", nil
	}
	return "", fmt.Errorf("unknown script kind %q", kind)
}
